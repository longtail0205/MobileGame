//        intro: 目が合った・話しかけたとき / lose: プレイヤーが勝ったとき（バトル画面）
//        win: プレイヤーが負けたとき / after: 撃破後に話しかけたとき
//   セリフは ひらがな多め・文節ごとに スペースを入れると GBA らしくなる。{player} は主人公の名前。
//
