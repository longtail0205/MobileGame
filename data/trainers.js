// トレーナーの定義（GameData.trainers）
//
// 【編集のしかた】
//   キー（例 route1_kenta）がトレーナーID。data/maps.js の npcs に
//   { id: 'xxx', x, y, dir, trainer: 'トレーナーID', sight: 視線マス数 } と書くと配置される。
